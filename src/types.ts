export type SubjectId = 'accounting' | 'statistics';

export interface Subject {
  id: SubjectId;
  name: string;
  icon: string; // Lucide icon name
  description: string;
  color: string;
}

export type Category = 'equity' | 'securities' | 'options' | 'dividend' | 'shares' | 'loans' | 'equity-method' | 'bonds' | 'descriptive' | 'probability' | 'inference' | 'formulas';

export interface Example {
  description: string;
  date: string;
  amount: string;
}

export interface CalculationRow {
  label: string;
  amount: string;
  isNegative?: boolean;
  isTotal?: boolean;
  isLoss?: boolean;
  tooltip?: string;
}

export interface Concept {
  term: string;
  definition: string;
}

export interface TheoryStep {
  title: string;
  formula?: string;
  calculation?: string;
  explanation: string;
  rows?: CalculationRow[];
}

export type BlockType = 'text' | 'formula' | 'example' | 'definition' | 'list';

export interface ContentBlock {
  type: BlockType;
  title?: string;
  content: string | string[];
  formula?: string;
  legend?: { symbol: string; description: string }[];
}

export interface TheoryGuide {
  id: string;
  subjectId: SubjectId;
  title: string;
  category: Category;
  description: string;
  introduction?: string;
  question?: string;
  concepts?: Concept[];
  blocks?: ContentBlock[];
  steps?: TheoryStep[];
  pages?: {
    title: string;
    blocks: ContentBlock[];
  }[];
}

export interface JournalEntry {
  id: string;
  subjectId: SubjectId;
  title: string;
  description: string;
  category: Category;
  entries: {
    account: string;
    debit?: string;
    credit?: string;
    note?: string;
  }[];
  explanation: string;
  examples: Example[];
  guideId?: string;
}

